const report = { at: new Date().toISOString(), checks: ["刷新恢复模型、用量与模拟时间", "正常发布保留模拟器输入", "同路径同组件重置还原用量，保留当前模型页面", "重置清除已删除记录的结果链接", "重置同步默认模拟器草稿"], oldTraceRemoved: oldTrace, errors };
await writeFile(new URL("../docs/verification-2026-09-26-round3/settings-reset-results.json", import.meta.url), JSON.stringify(report, null, 2));
