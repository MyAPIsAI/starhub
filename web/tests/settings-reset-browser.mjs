import { chromium } from "playwright";
import assert from "node:assert/strict";
import { writeFile } from "node:fs/promises";
const browser = await chromium.launch({ channel: "chrome", headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const errors = [];
page.on("pageerror", (error) => errors.push(String(error)));
await page.goto("http://127.0.0.1:5196/console/model-pricing?model=deepseek-chat");
await page.locator(".settings-pricing").waitFor();
await page.evaluate(async () => {
  const loaded = performance.getEntriesByType("resource").filter((e) => e.name.includes("/src/lib/product-preview.ts")).at(-1);
  window.__resetStore = (await import(loaded.name)).useProductPreview;
  window.__resetStore.getState().resetScenario("pricing");
});

await page.getByLabel("普通输入词元", { exact: true }).fill("9999");
await page.getByLabel("输出词元", { exact: true }).fill("77");
await page.getByLabel("计价模拟时间（本地时区）", { exact: true }).fill("2024-01-15T06:30");
await page.reload();
await page.locator(".settings-pricing").waitFor();
assert.ok(page.url().includes("model=deepseek-chat"));
assert.equal(await page.getByLabel("普通输入词元", { exact: true }).inputValue(), "9999");
assert.equal(await page.getByLabel("计价模拟时间（本地时区）", { exact: true }).inputValue(), "2024-01-15T06:30");
await page.getByLabel("DeepSeek V3 普通输入", { exact: true }).fill("0.28");
await page.getByRole("button", { name: "检查并发布", exact: true }).click();
await page.getByRole("button", { name: "确认发布", exact: true }).click();
assert.equal(await page.getByLabel("普通输入词元", { exact: true }).inputValue(), "9999");
assert.ok(page.url().includes("model=deepseek-chat"));
await page.getByRole("button", { name: "提交模拟用量并计费", exact: true }).click();
await page.getByRole("link", { name: "查看关联调用明细", exact: true }).waitFor();
const oldTrace = await page.getByRole("link", { name: "查看关联调用明细", exact: true }).getAttribute("href");
await page.evaluate(() => { document.querySelector(".settings-pricing").__sameMount = "same-mounted-form"; });
await page.evaluate(async () => { const loaded=performance.getEntriesByType("resource").filter(e=>e.name.includes("/src/lib/product-preview.ts")).at(-1); (await import(loaded.name)).useProductPreview.getState().resetScenario("pricing"); });
await page.waitForFunction(() => document.querySelector('.settings-usage-fields input')?.value === "1000");
assert.equal(await page.evaluate(() => document.querySelector(".settings-pricing").__sameMount), "same-mounted-form");
assert.equal(await page.getByLabel("普通输入词元", { exact: true }).inputValue(), "1000");
assert.equal(await page.getByLabel("输出词元", { exact: true }).inputValue(), "500");
assert.notEqual(await page.getByLabel("计价模拟时间（本地时区）", { exact: true }).inputValue(), "2024-01-15T06:30");
assert.equal(await page.getByRole("link", { name: "查看关联调用明细", exact: true }).count(), 0);
const persisted = await page.evaluate(() => JSON.parse(sessionStorage.getItem("veyra-metered-simulator-v1")));
assert.equal(persisted.modelId, "deepseek-chat");
assert.equal(persisted.usage.input_tokens, 1000);
await page.getByRole("button", { name: "演示场景与重置", exact: true }).click();
await page.getByRole("button", { name: "重置当前场景", exact: true }).click();
await page.getByRole("heading", {name:"标准模型",exact:true}).waitFor();
assert.equal(new URL(page.url()).search, "");
