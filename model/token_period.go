var ErrTokenPeriodPolicy = errors.New("invalid token quota period policy")
var ErrTokenPeriodBusy = errors.New("quota policy cannot change while reservations are pending")
var ErrQuotaReservation = errors.New("invalid or completed quota reservation")

// TokenQuotaPeriod retains the admission period even after a later rollover.
// Reserved quota is a hold; only UsedQuota contributes to lifetime consumption.
type TokenQuotaPeriod struct {
	QuotaLimitRemainderNano    int64  `gorm:"not null;default:0" json:"-"`
	UsedQuotaRemainderNano     int64  `gorm:"not null;default:0" json:"-"`
	ReservedQuotaRemainderNano int64  `gorm:"not null;default:0" json:"-"`
	CarryQuotaRemainderNano    int64  `gorm:"not null;default:0" json:"-"`
	ID                         int64  `gorm:"primaryKey" json:"id"`
	TokenID                    int64  `gorm:"index;not null" json:"token_id"`
	UserID                     int64  `gorm:"index;not null" json:"-"`
	Period                     string `json:"period"`
	Timezone                   string `json:"timezone"`
	Start                      int64  `gorm:"index" json:"start"`
	End                        int64  `json:"end"`
	QuotaLimit                 int64  `json:"quota_limit"`
	UsedQuota                  int64  `json:"used_quota"`
	ReservedQuota              int64  `json:"reserved_quota"`
	CarryQuota                 int64  `json:"carry_quota"`
	ClosedAt                   int64  `json:"closed_at"`
}

// QuotaReservation.ID is generated by the gateway, never supplied by a client.
// One reservation may be topped up by model fallback before being finalized.
type QuotaReservation struct {
	ID          string `gorm:"primaryKey;size:64"`
	UserID      int64  `gorm:"not null"`
	TokenID     int64  `gorm:"index;not null"`
	PeriodID    int64  `gorm:"index;not null;default:0"`
	Limited     bool
	Amount      int64
	AdmittedAt  int64
	CompletedAt int64 `gorm:"index;not null;default:0"`
	Released    bool
}

func tokenPeriodic(t *Token) bool { return t.QuotaPeriod == "daily" || t.QuotaPeriod == "monthly" }

func tokenPeriodBounds(period, timezone string, now time.Time) (int64, int64, error) {
	zone, err := time.LoadLocation(timezone)
	if err != nil {
		return 0, 0, ErrTokenPeriodPolicy
	}
	local := now.In(zone)
	day := local.Day()
	if period == "monthly" {
		day = 1
	} else if period != "daily" {
		return 0, 0, ErrTokenPeriodPolicy
	}
	start := time.Date(local.Year(), local.Month(), day, 0, 0, 0, 0, zone)
	end := start.AddDate(0, 0, 1)
	if period == "monthly" {
		end = start.AddDate(0, 1, 0)
	}
	return start.Unix(), end.Unix(), nil
}

func periodAvailable(p TokenQuotaPeriod) int64 {
	whole, _, err := common.NanoQuotaParts(periodMoneyAvailable(p))
	if err != nil {
		return 0
	}
	return whole
}

func syncTokenPeriod(tx *gorm.DB, t *Token, p TokenQuotaPeriod) error {
	t.QuotaPeriodID, t.PeriodStart, t.PeriodEnd = p.ID, p.Start, p.End
	used := common.QuotaMoney(p.UsedQuota, p.UsedQuotaRemainderNano)
	used.Add(used, common.QuotaMoney(p.CarryQuota, p.CarryQuotaRemainderNano))
	var err error
	t.PeriodUsedQuota, t.PeriodUsedQuotaRemainderNano, err = common.NanoQuotaParts(used)
	if err != nil {
		return err
	}
	t.PeriodReservedQuota, t.PeriodReservedQuotaRemainderNano = p.ReservedQuota, p.ReservedQuotaRemainderNano
	t.RemainQuota, t.RemainQuotaRemainderNano, err = common.NanoQuotaParts(periodMoneyAvailable(p))
	if err != nil {
		return err
	}
	return tx.Model(&Token{}).Where("id = ?", t.ID).Updates(map[string]any{
		"quota_period_id": p.ID, "period_start": p.Start, "period_end": p.End,
		"period_used_quota": t.PeriodUsedQuota, "period_reserved_quota": p.ReservedQuota, "remain_quota": t.RemainQuota,
		"period_used_quota_remainder_nano": t.PeriodUsedQuotaRemainderNano, "period_reserved_quota_remainder_nano": t.PeriodReservedQuotaRemainderNano, "remain_quota_remainder_nano": t.RemainQuotaRemainderNano,
	}).Error
}

func refreshTokenPeriod(tx *gorm.DB, t *Token, now time.Time) error {
	if !tokenPeriodic(t) {
		return nil
	}
	if t.QuotaPeriodID != 0 && now.Unix() < t.PeriodEnd {
		return nil
	}
	start, end, err := tokenPeriodBounds(t.QuotaPeriod, t.QuotaTimezone, now)
	if err != nil {
		return err
	}
	if t.QuotaPeriodID != 0 {
		if err := tx.Model(&TokenQuotaPeriod{}).Where("id = ? AND closed_at = 0", t.QuotaPeriodID).Update("closed_at", t.PeriodEnd).Error; err != nil {
			return err
		}
	}
	period := TokenQuotaPeriod{TokenID: t.ID, UserID: t.UserID, Period: t.QuotaPeriod, Timezone: t.QuotaTimezone, Start: start, End: end, QuotaLimit: t.PeriodQuotaLimit, QuotaLimitRemainderNano: t.PeriodQuotaLimitRemainderNano}
	if err := tx.Create(&period).Error; err != nil {
		return err
	}
	return syncTokenPeriod(tx, t, period)
}

// RefreshTokenQuota takes the writer before reading so two rollover workers
// cannot both create a fresh allowance at the same calendar boundary.
func RefreshTokenQuota(t *Token, now time.Time) error {
	if !tokenPeriodic(t) {
		return nil
	}
	return DB.Transaction(func(tx *gorm.DB) error {
		if err := tx.Model(&Token{}).Where("id = ?", t.ID).UpdateColumn("id", gorm.Expr("id")).Error; err != nil {
			return err
		}
		if err := tx.First(t, t.ID).Error; err != nil {
			return err
		}
		return refreshTokenPeriod(tx, t, now)
	})
}

func RefreshDueTokenPeriods(now time.Time, owner int64) error {
	for {
		var tokens []Token
		q := DB.Where("quota_period IN ? AND (period_end <= ? OR quota_period_id = 0)", []string{"daily", "monthly"}, now.Unix())
		if owner > 0 {
			q = q.Where("user_id = ?", owner)
		}
		if err := q.Order("id").Limit(500).Find(&tokens).Error; err != nil {
			return err
		}
		if len(tokens) == 0 {
			return nil
		}
		for i := range tokens {
			if err := RefreshTokenQuota(&tokens[i], now); err != nil {
				return err
			}
		}
	}
}

func periodPolicyFields(fields map[string]any) bool {
	for _, key := range []string{"quota_period", "period_quota_limit", "quota_region"} {
		if _, ok := fields[key]; ok {
			return true
		}
	}
	return false
}

// configureTokenPeriod runs in the same transaction as the guarded key edit.
// Schedule changes retain spent quota until the next real calendar boundary.
func configureTokenPeriod(tx *gorm.DB, t *Token, fields map[string]any, now time.Time) error {
	if !periodPolicyFields(fields) {
		if tokenPeriodic(t) {
			if _, ok := fields["remain_quota"]; ok {
				return ErrTokenPeriodPolicy
			}
			if flag, ok := fields["unlimited_quota"]; ok && flag == true {
				return ErrTokenPeriodPolicy
			}
		}
		return nil
	}
	next := *t
	if t.QuotaPeriodID == 0 && tokenPeriodic(t) {
		t.QuotaPeriod = "never"
		t.QuotaTimezone = "UTC"
	}
	if value, ok := fields["quota_period"].(string); ok {
		next.QuotaPeriod = value
	}
	if next.QuotaPeriod == "" {
		next.QuotaPeriod = "never"
	}
	if next.QuotaPeriod != "never" && next.QuotaPeriod != "daily" && next.QuotaPeriod != "monthly" {
		return ErrTokenPeriodPolicy
	}
	if value, ok := fields["period_quota_limit"].(int64); ok {
		next.PeriodQuotaLimit = value
		next.PeriodQuotaLimitRemainderNano = 0
	}
	if next.PeriodQuotaLimit < 0 || next.PeriodQuotaLimit > 9_007_199_254_740_991 {
		return ErrTokenPeriodPolicy
	}
	if value, ok := fields["quota_region"].(string); ok {
		next.QuotaRegion = value
	}
	if next.QuotaTimezone == "" {
		next.QuotaTimezone = "UTC"
	}
	_, regionChanged := fields["quota_region"]
	if regionChanged {
		next.QuotaTimezone = "UTC"
	}
	if regionChanged && next.QuotaRegion != "" {
		var region RegionProfile
		if err := tx.First(&region, "id = ? AND enabled = ?", next.QuotaRegion, true).Error; err != nil {
			return ErrTokenPeriodPolicy
		}
		next.QuotaTimezone = region.Timezone
	}
	if _, err := time.LoadLocation(next.QuotaTimezone); err != nil {
		return ErrTokenPeriodPolicy
	}
	if tokenPeriodic(&next) {
		if value, ok := fields["unlimited_quota"].(bool); ok && value {
			return ErrTokenPeriodPolicy
		}
		if _, ok := fields["remain_quota"]; ok {
			return ErrTokenPeriodPolicy
		}
		next.UnlimitedQuota = false
		fields["unlimited_quota"] = false
	}
	if err := refreshTokenPeriod(tx, t, now); err != nil {
		return err
	}
	scheduleChanged := next.QuotaPeriod != t.QuotaPeriod || next.QuotaTimezone != t.QuotaTimezone
	if scheduleChanged {
		var pending int64
		if err := tx.Model(&QuotaReservation{}).Where("token_id = ? AND completed_at = 0", t.ID).Count(&pending).Error; err != nil {
			return err
		}
		if pending > 0 {
			return ErrTokenPeriodBusy
		}
		if err := tx.Model(&QuotaSettlement{}).Where("token_id = ? AND completed_at = 0", t.ID).Count(&pending).Error; err != nil {
			return err
		}
		if pending > 0 {
			return ErrTokenPeriodBusy
		}
		tasks, err := SumPendingTaskQuota(tx, t.ID)
		if err != nil {
			return err
		}
		if tasks > 0 {
			return ErrTokenPeriodBusy
		}
	}
	fields["quota_period"], fields["period_quota_limit"], fields["quota_region"], fields["quota_timezone"] = next.QuotaPeriod, next.PeriodQuotaLimit, next.QuotaRegion, next.QuotaTimezone
	if !tokenPeriodic(&next) {
		if t.QuotaPeriodID > 0 {
			if err := tx.Model(&TokenQuotaPeriod{}).Where("id = ? AND closed_at = 0", t.QuotaPeriodID).Update("closed_at", now.Unix()).Error; err != nil {
				return err
			}
		}
		fields["quota_period_id"], fields["period_start"], fields["period_end"], fields["period_used_quota"], fields["period_reserved_quota"] = int64(0), int64(0), int64(0), int64(0), int64(0)
		fields["period_used_quota_remainder_nano"], fields["period_reserved_quota_remainder_nano"] = int64(0), int64(0)
		return nil
	}
	var period TokenQuotaPeriod
	if !scheduleChanged && t.QuotaPeriodID > 0 {
		if err := tx.First(&period, t.QuotaPeriodID).Error; err != nil {
			return err
		}
		required := common.QuotaMoney(period.UsedQuota, period.UsedQuotaRemainderNano)
		required.Add(required, common.QuotaMoney(period.CarryQuota, period.CarryQuotaRemainderNano))
		required.Add(required, common.QuotaMoney(period.ReservedQuota, period.ReservedQuotaRemainderNano))
		if common.QuotaMoney(next.PeriodQuotaLimit, next.PeriodQuotaLimitRemainderNano).Cmp(required) < 0 {
			return ErrTokenPeriodPolicy
		}
		period.QuotaLimit = next.PeriodQuotaLimit
		period.QuotaLimitRemainderNano = next.PeriodQuotaLimitRemainderNano
		if err := tx.Save(&period).Error; err != nil {
			return err
		}
	} else {
		start, end, err := tokenPeriodBounds(next.QuotaPeriod, next.QuotaTimezone, now)
		if err != nil {
			return err
		}
		if t.QuotaPeriodID > 0 {
			if err := tx.Model(&TokenQuotaPeriod{}).Where("id = ?", t.QuotaPeriodID).Update("closed_at", now.Unix()).Error; err != nil {
				return err
			}
		}
		carry := int64(0)
		carryRemainder := int64(0)
		if tokenPeriodic(t) {
			carry = t.PeriodUsedQuota
			carryRemainder = t.PeriodUsedQuotaRemainderNano
		}
		if common.QuotaMoney(next.PeriodQuotaLimit, next.PeriodQuotaLimitRemainderNano).Cmp(common.QuotaMoney(carry, carryRemainder)) < 0 {
			return ErrTokenPeriodPolicy
		}
		period = TokenQuotaPeriod{TokenID: t.ID, UserID: t.UserID, Period: next.QuotaPeriod, Timezone: next.QuotaTimezone, Start: start, End: end, QuotaLimit: next.PeriodQuotaLimit, QuotaLimitRemainderNano: next.PeriodQuotaLimitRemainderNano, CarryQuota: carry, CarryQuotaRemainderNano: carryRemainder}
		if err := tx.Create(&period).Error; err != nil {
			return err
		}
	}
	fields["quota_period_id"], fields["period_start"], fields["period_end"] = period.ID, period.Start, period.End
	used := common.QuotaMoney(period.UsedQuota, period.UsedQuotaRemainderNano)
	used.Add(used, common.QuotaMoney(period.CarryQuota, period.CarryQuotaRemainderNano))
	usedWhole, usedRemainder, err := common.NanoQuotaParts(used)
	if err != nil {
		return err
	}
	available, availableRemainder, err := common.NanoQuotaParts(periodMoneyAvailable(period))
	if err != nil {
		return err
	}
	fields["period_used_quota"], fields["period_reserved_quota"], fields["remain_quota"] = usedWhole, period.ReservedQuota, available
	fields["period_used_quota_remainder_nano"], fields["period_reserved_quota_remainder_nano"], fields["remain_quota_remainder_nano"], fields["period_quota_limit_remainder_nano"] = usedRemainder, period.ReservedQuotaRemainderNano, availableRemainder, period.QuotaLimitRemainderNano
	return nil
}

func reserveTokenAdmission(tx *gorm.DB, userID, tokenID int64, unlimited bool, amount int64, id string, now time.Time) error {
	var token Token
	if err := tx.First(&token, "id = ? AND user_id = ?", tokenID, userID).Error; err != nil {
		return err
	}
	if err := refreshTokenPeriod(tx, &token, now); err != nil {
		return err
	}
	if id == "" {
		if tokenPeriodic(&token) {
			return ErrQuotaReservation
		}
		return nil
	}
	if len(id) > 64 {
		return ErrQuotaReservation
	}
	var reservation QuotaReservation
	err := tx.First(&reservation, "id = ?", id).Error
	if errors.Is(err, gorm.ErrRecordNotFound) {
		reservation = QuotaReservation{ID: id, UserID: userID, TokenID: tokenID, PeriodID: token.QuotaPeriodID, Limited: !unlimited || tokenPeriodic(&token), AdmittedAt: now.Unix()}
	} else if err != nil {
		return err
	} else if reservation.UserID != userID || reservation.TokenID != tokenID || reservation.CompletedAt != 0 {
		return ErrQuotaReservation
	}
	if amount > math.MaxInt64-reservation.Amount {
		return ErrQuotaReservation
	}
	if reservation.PeriodID > 0 {
		var period TokenQuotaPeriod
		if err := tx.First(&period, reservation.PeriodID).Error; err != nil {
			return err
		}
		if periodAvailable(period) < amount {
			return ErrTokenQuotaShort
		}
		period.ReservedQuota += amount
		if err := tx.Save(&period).Error; err != nil {
			return err
		}
		if token.QuotaPeriodID == period.ID {
			if err := syncTokenPeriod(tx, &token, period); err != nil {
				return err
			}
		}
	}
	reservation.Amount += amount
	return tx.Save(&reservation).Error
}

func quotaAdmissionID(ids []string) string {
	if len(ids) > 0 {
		return ids[0]
	}
	return ""
}

func TokenPendingQuota(tx *gorm.DB, tokenID int64) (int64, error) {
	var held, legacy int64
	if err := tx.Model(&QuotaReservation{}).Where("token_id = ? AND completed_at = 0", tokenID).Select("COALESCE(SUM(amount),0)").Scan(&held).Error; err != nil {
		return 0, err
	}
	if err := tx.Model(&Task{}).Where("token_id = ? AND quota_reservation_id = '' AND status NOT IN ?", tokenID, []string{"succeeded", "failed", "cancelled"}).Select("COALESCE(SUM(quota),0)").Scan(&legacy).Error; err != nil {
		return 0, err
	}
	if legacy > math.MaxInt64-held {
		return 0, ErrQuotaReservation
	}
	return held + legacy, nil
}

func releaseTokenAdmission(tx *gorm.DB, userID, tokenID, amount int64, id string, now time.Time) error {
	// Lock before reading the receipt; retries cannot refund a reservation twice.
	if err := tx.Model(&User{}).Where("id = ?", userID).UpdateColumn("quota", gorm.Expr("quota")).Error; err != nil {
		return err
	}
	var r QuotaReservation
	if err := tx.First(&r, "id = ?", id).Error; err != nil {
		return err
	}
	if r.UserID != userID || r.TokenID != tokenID || r.Amount != amount {
		return ErrQuotaReservation
	}
	if r.CompletedAt != 0 {
		if r.Released {
			return nil
		}
		return ErrQuotaReservation
	}
	var token Token
	err := tx.First(&token, "id = ? AND user_id = ?", tokenID, userID).Error
	if err != nil && !errors.Is(err, gorm.ErrRecordNotFound) {
		return err
	}
	if token.ID > 0 {
		if err := refreshTokenPeriod(tx, &token, now); err != nil {
			return err
		}
	}
	if r.PeriodID > 0 {
		var period TokenQuotaPeriod
		if err := tx.First(&period, r.PeriodID).Error; err != nil {
			return err
		}
		if period.ReservedQuota < amount {
			return ErrQuotaReservation
		}
		period.ReservedQuota -= amount
		if err := tx.Save(&period).Error; err != nil {
			return err
		}
		if token.ID > 0 && token.QuotaPeriodID == period.ID {
			if err := syncTokenPeriod(tx, &token, period); err != nil {
				return err
			}
		}
	} else if r.Limited && token.ID > 0 {
		if err := tx.Model(&Token{}).Where("id = ?", tokenID).UpdateColumn("remain_quota", gorm.Expr("remain_quota + ?", amount)).Error; err != nil {
			return err
		}
	}
	if err := tx.Model(&User{}).Where("id = ?", userID).UpdateColumn("quota", gorm.Expr("quota + ?", amount)).Error; err != nil {
		return err
	}
	return tx.Model(&r).Updates(map[string]any{"completed_at": now.Unix(), "released": true}).Error
}

func settleTokenAdmission(tx *gorm.DB, token *Token, r QuotaReservation, delta, actual int64, entry *Log, now time.Time) error {
	if token.ID > 0 {
		if err := refreshTokenPeriod(tx, token, now); err != nil {
			return err
		}
	}
	var period TokenQuotaPeriod
	if err := tx.First(&period, r.PeriodID).Error; err != nil {
		return err
	}
	if period.TokenID != r.TokenID || period.UserID != r.UserID || period.ReservedQuota < r.Amount {
		return ErrQuotaReservation
	}
	collectedDelta := delta
	if delta > 0 {
		var user User
		if err := tx.First(&user, r.UserID).Error; err != nil {
			return err
		}
		collectedDelta = min(delta, max(int64(0), user.Quota), periodAvailable(period))
		if token.ID == 0 {
			collectedDelta = 0
		}
	}
	entry.UnfundedQuota = delta - collectedDelta
	entry.Quota = actual - entry.UnfundedQuota
	if err := tx.Model(&User{}).Where("id = ?", r.UserID).UpdateColumn("quota", gorm.Expr("quota - ?", collectedDelta)).Error; err != nil {
		return err
	}
	period.ReservedQuota -= r.Amount
	period.UsedQuota += entry.Quota
	if err := tx.Save(&period).Error; err != nil {
		return err
	}
	if token.ID > 0 && token.QuotaPeriodID == period.ID {
		return syncTokenPeriod(tx, token, period)
	}
	return nil
}
